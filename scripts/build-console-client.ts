import { createHash } from "node:crypto";
import { consoleAssetBytes } from "./console-asset-metrics";
import { projectDesignTokens } from "./design-tokens";
import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync, mkdtempSync, mkdirSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
const buildDirectory = mkdtempSync(join(tmpdir(), "mini-console-"));
const output = writeFileSync;
try {
mkdirSync("src/console/generated", { recursive: true });
const tokens = await projectDesignTokens();
output("src/console/generated/tokens.css", tokens.css);
const outfile = join(buildDirectory, "console.js");
const built = spawnSync("node_modules/.bin/esbuild", [
  "src/console/client/main.tsx",
  "--bundle",
  "--format=esm",
  "--minify",
  "--target=es2022",
  "--jsx=automatic",
  `--outfile=${outfile}`,
  "--define:process.env.NODE_ENV=\"production\"",
  "--legal-comments=eof"
], { stdio: "inherit" });
if (built.status !== 0) throw new Error("Console client compilation failed.");
const code = readFileSync(outfile, "utf8");
if (!code.trim()) throw new Error("Console client bundle is empty.");
const digest = createHash("sha256").update(code).digest("hex");
output(
  "src/console/generated/console-client.ts",
  `/** Generated by scripts/build-console-client.ts. Do not edit. */\nexport const consoleClientSource = ${JSON.stringify(code)};\nexport const consoleClientDigest = ${JSON.stringify(digest)};\n`
);
console.log("console client bytes", consoleAssetBytes(code));
const bootstrapFile = join(buildDirectory, "bootstrap.js");
const bootstrap = spawnSync("node_modules/.bin/esbuild", [
  "src/console/client/bootstrap.ts", "--bundle", "--format=iife", "--minify", "--target=es2022",
  `--define:CONSOLE_RUNTIME_PATH=${JSON.stringify(`/admin/console-${digest}.js`)}`,
  `--outfile=${bootstrapFile}`
], { stdio: "inherit" });
if (bootstrap.status !== 0) throw new Error("Console bootstrap compilation failed.");
output("src/console/generated/console-bootstrap.ts", `/** Generated by scripts/build-console-client.ts. Do not edit. */\nexport const consoleBootstrapSource = ${JSON.stringify(readFileSync(bootstrapFile, "utf8"))};\n`);

const cssFile = join(buildDirectory, "console.css");
const styles = spawnSync("node_modules/.bin/tailwindcss", ["-i", "src/console/console.css", "-o", cssFile, "--minify"], {stdio: "inherit"});
if (styles.status !== 0) throw new Error("Console style compilation failed.");
const css = readFileSync(cssFile, "utf8");
console.log("console CSS bytes", consoleAssetBytes(css));
output("src/console/generated/console-styles.ts", `/** Generated from tokens/console.resolver.json and src/console/console.css. Do not edit. */\nexport const consoleStyles = ${JSON.stringify(css)};\nexport const consoleStylesDigest = ${JSON.stringify(createHash("sha256").update(css).digest("hex"))};\nexport const consoleTheme = ${JSON.stringify(tokens.theme)};\n`);
} finally { rmSync(buildDirectory, {recursive: true, force: true}); }
